-- CloudBase-only opaque-token identity store. Never reads or updates public.users.
-- Apply after 001 defines veil_archive_assert_service_role().
-- API keys and plaintext access/refresh tokens are never stored in these tables.
BEGIN;

CREATE TABLE IF NOT EXISTS public.veil_archive_auth_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL UNIQUE,
  email text UNIQUE,
  nickname text NOT NULL,
  password_hash text,
  is_admin boolean NOT NULL DEFAULT false,
  is_active boolean NOT NULL DEFAULT true,
  is_guest boolean NOT NULL DEFAULT false,
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (username ~ '^[a-z0-9_]{3,50}$'),
  CHECK ((is_guest AND NOT is_admin AND password_hash IS NULL AND expires_at IS NOT NULL)
         OR (NOT is_guest AND password_hash IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS public.veil_archive_auth_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.veil_archive_auth_users(id),
  access_hash text NOT NULL UNIQUE CHECK (access_hash ~ '^[a-f0-9]{64}$'),
  refresh_hash text NOT NULL UNIQUE CHECK (refresh_hash ~ '^[a-f0-9]{64}$'),
  access_expires_at timestamptz NOT NULL,
  refresh_expires_at timestamptz NOT NULL,
  revoked_at timestamptz,
  rotated_to bigint REFERENCES public.veil_archive_auth_sessions(id),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (access_hash <> refresh_hash),
  CHECK (access_expires_at <= refresh_expires_at)
);
CREATE INDEX IF NOT EXISTS veil_archive_auth_sessions_owner ON public.veil_archive_auth_sessions(user_id);
CREATE INDEX IF NOT EXISTS veil_archive_auth_sessions_expiry ON public.veil_archive_auth_sessions(refresh_expires_at);

CREATE TABLE IF NOT EXISTS public.veil_archive_auth_rate_windows (
  namespace text NOT NULL,
  identity_hash text NOT NULL CHECK (identity_hash ~ '^[a-f0-9]{64}$'),
  attempts bigint NOT NULL CHECK (attempts > 0),
  expires_at timestamptz NOT NULL,
  PRIMARY KEY (namespace, identity_hash)
);

ALTER TABLE public.veil_archive_auth_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.veil_archive_auth_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.veil_archive_auth_rate_windows ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.veil_archive_auth_users, public.veil_archive_auth_sessions,
  public.veil_archive_auth_rate_windows FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE public.veil_archive_auth_users_id_seq,
  public.veil_archive_auth_sessions_id_seq FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_take_rate(
  p_namespace text, p_identity_hash text, p_limit integer, p_window_seconds integer
) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_count bigint; v_now timestamptz := clock_timestamp();
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  IF p_namespace IS NULL OR p_namespace NOT IN ('guest-client','guest-global','login-client','login-account','refresh-client')
     OR p_identity_hash IS NULL OR p_identity_hash !~ '^[a-f0-9]{64}$'
     OR p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 2000
     OR p_window_seconds IS NULL OR p_window_seconds NOT BETWEEN 1 AND 86400 THEN
    RAISE EXCEPTION 'AUTH_RATE_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;
  INSERT INTO public.veil_archive_auth_rate_windows(namespace, identity_hash, attempts, expires_at)
  VALUES (p_namespace, p_identity_hash, 1, v_now + make_interval(secs => p_window_seconds))
  ON CONFLICT (namespace, identity_hash) DO UPDATE SET
    attempts = CASE WHEN public.veil_archive_auth_rate_windows.expires_at <= v_now
                    THEN 1 ELSE LEAST(public.veil_archive_auth_rate_windows.attempts + 1, 1000000) END,
    expires_at = CASE WHEN public.veil_archive_auth_rate_windows.expires_at <= v_now
                      THEN EXCLUDED.expires_at ELSE public.veil_archive_auth_rate_windows.expires_at END
  RETURNING attempts INTO v_count;
  RETURN v_count <= p_limit;
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_user_json(p_user_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_result jsonb;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  SELECT jsonb_build_object('id', u.id, 'username', u.username, 'email', u.email,
    'nickname', u.nickname, 'is_admin', u.is_admin, 'is_active', u.is_active,
    'is_guest', u.is_guest) INTO v_result
  FROM public.veil_archive_auth_users AS u WHERE u.id = p_user_id;
  RETURN v_result;
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_issue(
  p_user_id bigint, p_access_hash text, p_refresh_hash text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_user public.veil_archive_auth_users%ROWTYPE;
  v_now timestamptz := clock_timestamp(); v_refresh_exp timestamptz; v_access_exp timestamptz;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  IF p_access_hash IS NULL OR p_refresh_hash IS NULL
     OR p_access_hash !~ '^[a-f0-9]{64}$' OR p_refresh_hash !~ '^[a-f0-9]{64}$'
     OR p_access_hash = p_refresh_hash THEN
    RAISE EXCEPTION 'AUTH_TOKEN_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_user FROM public.veil_archive_auth_users WHERE id = p_user_id FOR UPDATE;
  IF NOT FOUND OR NOT v_user.is_active OR (v_user.expires_at IS NOT NULL AND v_user.expires_at <= v_now) THEN
    RETURN jsonb_build_object('ok', false, 'status', 401, 'code', 'AUTH_SESSION_INVALID');
  END IF;
  v_refresh_exp := LEAST(v_now + interval '30 days', COALESCE(v_user.expires_at, 'infinity'::timestamptz));
  v_access_exp := LEAST(v_now + interval '2 hours', v_refresh_exp);
  INSERT INTO public.veil_archive_auth_sessions(user_id, access_hash, refresh_hash, access_expires_at, refresh_expires_at)
  VALUES (p_user_id, p_access_hash, p_refresh_hash, v_access_exp, v_refresh_exp);
  RETURN jsonb_build_object('ok', true, 'expires_in', GREATEST(1, floor(extract(epoch FROM v_access_exp - v_now))::integer),
    'user', public.veil_archive_auth_user_json(p_user_id));
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_guest(
  p_username text, p_access_hash text, p_refresh_hash text, p_client_hash text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_id bigint; v_count bigint;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  IF p_username IS NULL OR p_username !~ '^guest_[a-f0-9]{32}$' THEN
    RAISE EXCEPTION 'AUTH_GUEST_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;
  IF NOT public.veil_archive_auth_take_rate('guest-client', p_client_hash, 20, 3600)
     OR NOT public.veil_archive_auth_take_rate('guest-global', repeat('0',64), 100, 3600) THEN
    RETURN jsonb_build_object('ok', false, 'status', 429, 'code', 'AUTH_GUEST_RATE_LIMIT');
  END IF;
  SELECT count(*) INTO v_count FROM public.veil_archive_auth_users
    WHERE is_guest AND is_active AND expires_at > clock_timestamp();
  IF v_count >= 2000 THEN
    RETURN jsonb_build_object('ok', false, 'status', 503, 'code', 'AUTH_GUEST_CAPACITY');
  END IF;
  INSERT INTO public.veil_archive_auth_users(username,nickname,is_guest,is_admin,expires_at)
  VALUES (p_username, '试玩访客', true, false, clock_timestamp() + interval '24 hours') RETURNING id INTO v_id;
  RETURN public.veil_archive_auth_issue(v_id, p_access_hash, p_refresh_hash);
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_credentials(
  p_login text, p_login_hash text, p_client_hash text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_user public.veil_archive_auth_users%ROWTYPE;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  IF p_login IS NULL OR length(p_login) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'AUTH_LOGIN_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;
  IF NOT public.veil_archive_auth_take_rate('login-client',p_client_hash,20,300)
     OR NOT public.veil_archive_auth_take_rate('login-account',p_login_hash,5,300) THEN
    RETURN jsonb_build_object('ok',false,'status',429,'code','AUTH_LOGIN_RATE_LIMIT');
  END IF;
  SELECT * INTO v_user FROM public.veil_archive_auth_users
    WHERE NOT is_guest AND (username = lower(p_login) OR email = lower(p_login)) LIMIT 1;
  RETURN jsonb_build_object('ok', true,
    'user', CASE WHEN v_user.id IS NULL THEN NULL ELSE public.veil_archive_auth_user_json(v_user.id) END,
    'password_hash', CASE WHEN v_user.is_active THEN v_user.password_hash ELSE NULL END);
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_login_complete(
  p_user_id bigint, p_expected_password_hash text, p_login_hash text,
  p_access_hash text, p_refresh_hash text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_user public.veil_archive_auth_users%ROWTYPE;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  SELECT * INTO v_user FROM public.veil_archive_auth_users WHERE id = p_user_id FOR UPDATE;
  IF NOT FOUND OR v_user.is_guest OR NOT v_user.is_active
     OR p_expected_password_hash IS NULL OR v_user.password_hash IS DISTINCT FROM p_expected_password_hash THEN
    RETURN jsonb_build_object('ok',false,'status',401,'code','AUTH_INVALID_CREDENTIALS');
  END IF;
  DELETE FROM public.veil_archive_auth_rate_windows WHERE namespace='login-account' AND identity_hash=p_login_hash;
  RETURN public.veil_archive_auth_issue(p_user_id,p_access_hash,p_refresh_hash);
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_me(p_access_hash text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_id bigint;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  SELECT s.user_id INTO v_id FROM public.veil_archive_auth_sessions s
    JOIN public.veil_archive_auth_users u ON u.id=s.user_id
    WHERE s.access_hash=p_access_hash AND s.revoked_at IS NULL
      AND s.access_expires_at > clock_timestamp() AND u.is_active
      AND (u.expires_at IS NULL OR u.expires_at > clock_timestamp());
  IF v_id IS NULL THEN
    RETURN jsonb_build_object('ok',false,'status',401,'code','AUTH_SESSION_INVALID');
  END IF;
  RETURN jsonb_build_object('ok',true,'user',public.veil_archive_auth_user_json(v_id));
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_refresh(
  p_old_refresh_hash text, p_access_hash text, p_refresh_hash text, p_client_hash text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_old public.veil_archive_auth_sessions%ROWTYPE; v_result jsonb; v_new_id bigint;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  IF NOT public.veil_archive_auth_take_rate('refresh-client',p_client_hash,60,300) THEN
    RETURN jsonb_build_object('ok',false,'status',429,'code','AUTH_REFRESH_RATE_LIMIT');
  END IF;
  SELECT * INTO v_old FROM public.veil_archive_auth_sessions WHERE refresh_hash=p_old_refresh_hash FOR UPDATE;
  IF NOT FOUND OR v_old.revoked_at IS NOT NULL OR v_old.refresh_expires_at <= clock_timestamp() THEN
    RETURN jsonb_build_object('ok',false,'status',401,'code','AUTH_REFRESH_INVALID');
  END IF;
  -- One RPC transaction: the locked original session can be consumed only once.
  -- Hash collisions or issue failures raise/return before any successful rotation.
  v_result := public.veil_archive_auth_issue(v_old.user_id,p_access_hash,p_refresh_hash);
  IF v_result->>'ok' IS DISTINCT FROM 'true' THEN RETURN v_result; END IF;
  SELECT id INTO v_new_id FROM public.veil_archive_auth_sessions WHERE refresh_hash=p_refresh_hash;
  UPDATE public.veil_archive_auth_sessions SET revoked_at=clock_timestamp(),rotated_to=v_new_id WHERE id=v_old.id;
  RETURN v_result;
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_logout(p_access_hash text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_id bigint;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  UPDATE public.veil_archive_auth_sessions SET revoked_at=COALESCE(revoked_at,clock_timestamp())
    WHERE access_hash=p_access_hash RETURNING id INTO v_id;
  RETURN jsonb_build_object('ok',true,'token_revoked',v_id IS NOT NULL);
END $$;

CREATE OR REPLACE FUNCTION public.veil_archive_auth_bootstrap(
  p_username text,p_email text,p_password_hash text,p_is_admin boolean DEFAULT false
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog AS $$
DECLARE v_id bigint;
BEGIN
  PERFORM public.veil_archive_assert_service_role();
  IF p_username IS NULL OR p_username !~ '^[a-z0-9_]{3,50}$'
     OR p_email IS NULL OR length(p_email) NOT BETWEEN 3 AND 100
     OR p_email <> lower(p_email) OR p_password_hash IS NULL
     OR left(p_password_hash,10) <> '$argon2id$' OR length(p_password_hash)>512 THEN
    RAISE EXCEPTION 'AUTH_BOOTSTRAP_INPUT_INVALID' USING ERRCODE = '22023';
  END IF;
  INSERT INTO public.veil_archive_auth_users(username,email,nickname,password_hash,is_admin,is_guest)
  VALUES(p_username,p_email,p_username,p_password_hash,COALESCE(p_is_admin,false),false)
  ON CONFLICT DO NOTHING RETURNING id INTO v_id;
  IF v_id IS NULL THEN
    RETURN jsonb_build_object('ok',false,'status',409,'code','AUTH_ACCOUNT_EXISTS');
  END IF;
  RETURN jsonb_build_object('ok',true,'user',public.veil_archive_auth_user_json(v_id));
END $$;

-- RLS has no browser policies. Only service_role may execute these definer RPCs;
-- all RPCs also independently verify the trusted PostgREST JWT role claim.
DO $$ DECLARE f record;
BEGIN
  FOR f IN SELECT p.oid::regprocedure AS signature FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.proname ~ '^veil_archive_auth_'
  LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated',f.signature);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role',f.signature);
  END LOOP;
END $$;
COMMIT;
